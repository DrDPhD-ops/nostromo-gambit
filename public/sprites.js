export const SETS = {
  classic: { w: CLASSIC, b: CLASSIC },
  xeno: { w: MARINES, b: XENO },
};

const cache = new Map();

/**
 * Разворачивает битмап в SVG. Соседние пиксели одного цвета склеиваются в один
 * прямоугольник по горизонтали: без этого на доску уходило бы больше четырёх тысяч
 * узлов DOM только под фигуры.
 */
export function spriteSvg(setName, color, type) {
  const key = `${setName}:${color}:${type}`;
  if (cache.has(key)) return cache.get(key);

  const set = SETS[setName] || SETS.xeno;
  const rows = (set[color] || set.w)[type] || CLASSIC[type];
  const palette = PALETTES[color];
  const parts = [];

  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.' || ch === ' ') {
        x += 1;
        continue;
      }
      let run = 1;
      while (x + run < row.length && row[x + run] === ch) run += 1;
      const fill = palette[ch] || palette['#'];
      parts.push(`<rect x="${x}" y="${y}" width="${run}" height="1" fill="${fill}"/>`);
      x += run;
    }
  }

  const svg =
    `<svg viewBox="0 0 16 16" xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges" ` +
    `preserveAspectRatio="xMidYMid meet">${parts.join('')}</svg>`;
  cache.set(key, svg);
  return svg;
}

